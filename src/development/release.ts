import { randomUUID } from "node:crypto";
import { mkdir, open, realpath, rename, rm, rmdir } from "node:fs/promises";
import { basename, dirname, join } from "node:path";
import { runtimeIdentity, validateSupportedRuntime, type RuntimeValidator } from "./policy.js";
import { assertFreshArtifact, type FreshArtifact } from "./freshness.js";
import type { Jobs } from "./jobs.js";
import type { ToolchainReport } from "./toolchain.js";
export class ReleaseError extends Error {
  constructor(public readonly code: "unsupported-runtime" | "output-exists" | "output-parent-missing" | "output-not-canonical" | "invalid-script-value", message: string) { super(`${code}: ${message}`); this.name = "ReleaseError"; }
}
export type ReleaseArgument = string | number | boolean;
export type ReleaseFee = { method: "fee_juice" } | { method: "fpc-sponsored"; fpcAddress: string };
export interface PackageInput {
  buildJobId: string;
  artifactPath: string;
  installationRoot: string;
  nodeExecutable: string;
  outputDirectory: string;
  args: ReleaseArgument[];
  initialize: boolean;
  initializerName?: string;
  account: string;
  fee: ReleaseFee;
  nodeUrl: string;
  contractAlias?: string;
}
export interface ReleaseManifest {
  schemaVersion: 1;
  generatedAt: string;
  build: { jobId: string; kind: "compile" | "test"; projectPath: string; provenanceHash: string };
  artifact: { path: string; sha256: string; contractName: string };
  deployment: { args: ReleaseArgument[]; initialize: boolean; initializerName?: string; account: string; contractAlias: string; nodeUrl: string };
  fee: ReleaseFee;
  toolchain: { installationRoot: string; nodeExecutable: string; runtimeIdentity: string; cli: { path: string; identity?: string } };
}
export interface PackageResult {
  outputDirectory: string;
  files: { script: string; checklist: string; manifest: string };
  manifest: ReleaseManifest;
}
export const scriptSafe = (value: string): boolean => !value.startsWith("-") && !/[\x00-\x1f\x7f]/.test(value);
function walletLauncher(runtime: ToolchainReport): string {
  if (!runtime.cli.path) throw new ReleaseError("unsupported-runtime", "The selected runtime has no aztec CLI launcher.");
  return join(dirname(runtime.cli.path), "aztec-wallet");
}
export function renderManifest(input: PackageInput, fresh: FreshArtifact, runtime: ToolchainReport, wallet: string, generatedAt: string): ReleaseManifest {
  const contractName = fresh.artifact.contractName ?? basename(fresh.artifact.path, ".json");
  return {
    schemaVersion: 1,
    generatedAt,
    build: { jobId: input.buildJobId, kind: fresh.kind, projectPath: fresh.projectPath, provenanceHash: fresh.artifact.provenanceHash },
    artifact: { path: fresh.artifact.path, sha256: fresh.artifact.contentHash, contractName },
    deployment: {
      args: [...input.args], initialize: input.initialize, ...(input.initializerName === undefined ? {} : { initializerName: input.initializerName }),
      account: input.account, contractAlias: input.contractAlias ?? contractName.toLowerCase(), nodeUrl: input.nodeUrl,
    },
    fee: input.fee.method === "fpc-sponsored" ? { method: "fpc-sponsored", fpcAddress: input.fee.fpcAddress } : { method: "fee_juice" },
    toolchain: {
      installationRoot: runtime.installationRoot, nodeExecutable: runtime.runtimeNode.path, runtimeIdentity: runtimeIdentity(runtime),
      cli: { path: wallet, ...(runtime.cli.identity === undefined ? {} : { identity: runtime.cli.identity }) },
    },
  };
}
const quote = (value: string): string => `'${value.replaceAll("'", "'\\''")}'`;
function paymentString(fee: ReleaseFee): string {
  return fee.method === "fpc-sponsored" ? `method=fpc-sponsored,fpc=${fee.fpcAddress}` : "method=fee_juice";
}
export function renderDeployScript(manifest: ReleaseManifest): string {
  const { deployment, artifact, toolchain } = manifest;
  if (!/^\d{4}-\d{2}-\d{2}T[0-9:.]+Z$/.test(manifest.generatedAt)) throw new ReleaseError("invalid-script-value", "generatedAt is not an ISO 8601 UTC timestamp.");
  const flagged = [deployment.account, deployment.contractAlias, deployment.initializerName, ...deployment.args.map(String)].filter(value => value !== undefined);
  if (!flagged.every(scriptSafe)) throw new ReleaseError("invalid-script-value", "A value that follows a wallet flag begins with '-' or has a control character.");
  let initializer: string | undefined;
  if (!deployment.initialize) initializer = "--no-init";
  else if (deployment.initializerName !== undefined) initializer = `--init ${quote(deployment.initializerName)}`;
  const lines = [
    "#!/usr/bin/env bash",
    `# Generated by aztec-mcp aztec_dev_release on ${manifest.generatedAt}.`,
    "# Review every value below before you run this script. It spends funds from the",
    "# account named in ACCOUNT.",
    "set -euo pipefail",
    "",
    `NODE_URL=${quote(deployment.nodeUrl)}`,
    `ACCOUNT=${quote(deployment.account)}`,
    `PAYMENT=${quote(paymentString(manifest.fee))}`,
    `CONTRACT_ALIAS=${quote(deployment.contractAlias)}`,
    "",
    `WALLET=${quote(toolchain.cli.path)}`,
    `ARTIFACT=${quote(artifact.path)}`,
    `EXPECTED_SHA256=${quote(artifact.sha256)}`,
    "",
    "if command -v sha256sum >/dev/null 2>&1; then",
    `  ACTUAL_SHA256="$(sha256sum "$ARTIFACT" | cut -d' ' -f1)"`,
    "else",
    `  ACTUAL_SHA256="$(shasum -a 256 "$ARTIFACT" | cut -d' ' -f1)"`,
    "fi",
    `if [ "$ACTUAL_SHA256" != "$EXPECTED_SHA256" ]; then`,
    `  echo "Artifact hash changed since packaging. Compile and package again." >&2`,
    "  exit 1",
    "fi",
    "",
    `"$WALLET" deploy "$ARTIFACT" \\`,
    `  --node-url "$NODE_URL" \\`,
    `  --from "$ACCOUNT" \\`,
    `  --alias "$CONTRACT_ALIAS" \\`,
    ...(initializer === undefined ? [] : [`  ${initializer} \\`]),
    ...(deployment.args.length === 0 ? [] : [`  --args ${deployment.args.map(value => quote(String(value))).join(" ")} \\`]),
    `  --payment "$PAYMENT" \\`,
    "  --wait-for-status proposed \\",
    "  --json",
  ];
  return `${lines.join("\n")}\n`;
}
export function renderChecklist(manifest: ReleaseManifest, scriptPath: string): string {
  const { deployment, artifact, toolchain, fee } = manifest;
  const wallet = quote(toolchain.cli.path);
  const node = quote(deployment.nodeUrl);
  const account = quote(deployment.account);
  const payment = quote(paymentString(fee));
  const feeStep = fee.method === "fpc-sponsored"
    ? `Confirm the fee method. This release pays through the sponsor \`${fee.fpcAddress}\`. Confirm it is the address the network publishes for this release.`
    : "Confirm the fee method. This release pays with fee juice. Confirm the fee juice balance of the account is above zero.";
  const lines = [
    `# Release checklist for ${artifact.contractName}`,
    "",
    "## Before you run",
    "",
    `1. Confirm the target node version matches the toolchain. The CLI version is \`${toolchain.cli.identity ?? "unknown"}\`. Ask the node for its version and compare \`nodeVersion\` with it. A mismatch can make the deployment fail.`,
    "",
    "   ```bash",
    `   curl -s -X POST ${node} -H 'content-type: application/json' -d '{"jsonrpc":"2.0","id":1,"method":"node_getNodeInfo","params":[]}'`,
    "   ```",
    "",
    `2. Confirm the account \`${deployment.account}\` exists in this wallet's data directory. If the account does not exist yet, create it. \`create-account\` registers and deploys the account in one step. Use \`deploy-account\` only for an account that was registered with \`--register-only\`.`,
    "",
    "   ```bash",
    `   ${wallet} create-account --node-url ${node} --alias ${account} --payment ${payment}`,
    `   ${wallet} deploy-account ${account} --node-url ${node} --payment ${payment}`,
    "   ```",
    "",
    `3. ${feeStep}`,
    `4. Read the script \`${scriptPath}\`. Every value in its variable block is yours to change.`,
    "",
    "## Run",
    "",
    "1. Run the script:",
    "",
    "   ```bash",
    `   bash ${quote(scriptPath)}`,
    "   ```",
    "",
    "## After",
    "",
    "1. Record the printed address and transaction hash in your project.",
    "2. Confirm the receipt. Replace `<txHash>` with the recorded hash:",
    "",
    "   ```bash",
    `   ${wallet} --node-url ${node} get-tx <txHash>`,
    "   ```",
    "",
    "3. Register the contract in any other wallet. Replace `<address>` with the recorded address:",
    "",
    "   ```bash",
    `   ${wallet} register-contract <address> ${quote(artifact.path)} --node-url ${node}`,
    "   ```",
    "",
    `4. Keep \`${join(dirname(scriptPath), "manifest.json")}\` with the deployed address. It ties the deployment to the verified build.`,
  ];
  return `${lines.join("\n")}\n`;
}
async function createOutputDirectory(path: string): Promise<void> {
  try { await mkdir(path, { mode: 0o700 }); } catch (error) {
    const code = (error as NodeJS.ErrnoException).code;
    if (code === "EEXIST") throw new ReleaseError("output-exists", "outputDirectory already exists; select a new directory.");
    if (code === "ENOENT") throw new ReleaseError("output-parent-missing", "The parent of outputDirectory does not exist.");
    throw error;
  }
  if (await realpath(path) !== path) {
    await rmdir(path);
    throw new ReleaseError("output-not-canonical", "outputDirectory resolves to a different path; pass the resolved path (realpath) instead.");
  }
}
async function writeExclusive(path: string, content: string, mode: number): Promise<void> {
  const temporary = `${path}.${randomUUID()}.tmp`;
  const handle = await open(temporary, "wx", mode);
  try {
    await handle.chmod(mode);
    await handle.writeFile(content);
    await handle.close();
    await rename(temporary, path);
  } catch (error) {
    await handle.close().catch(() => undefined);
    await rm(temporary, { force: true });
    throw error;
  }
}
export class ReleaseService {
  constructor(private readonly validateRuntime: RuntimeValidator = validateSupportedRuntime, private readonly jobs: Jobs, private readonly now = () => new Date(), private readonly write = writeExclusive) { }
  async package(input: PackageInput): Promise<PackageResult> {
    const selection = { installationRoot: input.installationRoot, nodeExecutable: input.nodeExecutable };
    const runtime = await this.validateRuntime(selection);
    const wallet = walletLauncher(runtime);
    const fresh = await assertFreshArtifact({ jobs: this.jobs, buildJobId: input.buildJobId, artifactPath: input.artifactPath, runtime });
    const manifest = renderManifest(input, fresh, runtime, wallet, this.now().toISOString());
    const files = { script: join(input.outputDirectory, "deploy.sh"), checklist: join(input.outputDirectory, "CHECKLIST.md"), manifest: join(input.outputDirectory, "manifest.json") };
    const contents = { manifest: `${JSON.stringify(manifest, null, 2)}\n`, script: renderDeployScript(manifest), checklist: renderChecklist(manifest, files.script) };
    await createOutputDirectory(input.outputDirectory);
    try {
      await this.write(files.manifest, contents.manifest, 0o600);
      await this.write(files.script, contents.script, 0o700);
      await this.write(files.checklist, contents.checklist, 0o600);
    } catch (error) {
      await rm(input.outputDirectory, { recursive: true, force: true }).catch(() => undefined);
      throw error;
    }
    return { outputDirectory: input.outputDirectory, files, manifest };
  }
}
